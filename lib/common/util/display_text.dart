/// 把 B 站标题里常见的「花体/全角」装饰字符还原成普通字符。
///
/// 这类字符（数学字母、全角字母数字、特殊花体）在部分 Android 字体里缺字形，
/// 会显示成方块或乱码，例如 `𝐇𝐢-𝐑𝐞𝐬`、`ＡＢＣ`。
String normalizeDisplayText(String value) {
  if (value.isEmpty) {
    return value;
  }
  final StringBuffer buffer = StringBuffer();
  for (final int rune in value.runes) {
    buffer.write(_normalizeRune(rune));
  }
  return buffer.toString();
}

String _normalizeRune(int rune) {
  if (rune < 0x00A0) {
    return String.fromCharCode(rune);
  }
  if (rune >= 0xFF01 && rune <= 0xFF5E) {
    return String.fromCharCode(rune - 0xFEE0);
  }
  if (rune == 0x3000) {
    return ' ';
  }
  final String? letter = _mathLetterlikeMap[rune];
  if (letter != null) {
    return letter;
  }
  for (final (int start, int end, int base) in _linearRanges) {
    if (rune >= start && rune <= end) {
      return String.fromCharCode(base + (rune - start));
    }
  }
  return String.fromCharCode(rune);
}

